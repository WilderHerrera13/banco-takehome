-- ---------------------------------------------------------------------
-- Base de datos del microservicio de Account y Movement
-- ---------------------------------------------------------------------
CREATE DATABASE banco_ms2;

\connect banco_ms2

CREATE TABLE account (
    account_number VARCHAR(30)   NOT NULL,
    account_type   VARCHAR(20)   NOT NULL,
    initial_balance NUMERIC(19,2) NOT NULL,
    current_balance  NUMERIC(19,2) NOT NULL,
    active        BOOLEAN       NOT NULL DEFAULT TRUE,
    client_id    VARCHAR(40)   NOT NULL,
    version       BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT pk_cuenta PRIMARY KEY (account_number),
    CONSTRAINT ck_cuenta_tipo CHECK (account_type IN ('SAVINGS', 'CURRENT'))
);

CREATE TABLE movement (
    movement_id    BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    date            DATE          NOT NULL,
    movement_type  VARCHAR(20)   NOT NULL,
    amount            NUMERIC(19,2) NOT NULL,
    balance            NUMERIC(19,2) NOT NULL,
    account_number    VARCHAR(30)   NOT NULL,
    CONSTRAINT pk_movimiento PRIMARY KEY (movement_id),
    CONSTRAINT fk_movimiento_cuenta FOREIGN KEY (account_number) REFERENCES account (account_number),
    CONSTRAINT ck_movimiento_tipo CHECK (movement_type IN ('DEPOSIT', 'WITHDRAWAL'))
);

CREATE INDEX idx_movimiento_cuenta_fecha ON movement (account_number, date);
CREATE INDEX idx_cuenta_cliente ON account (client_id);

-- Proyeccion local de los clients recibidos por el evento de dominio.
CREATE TABLE client_projection (
    client_id     VARCHAR(40) NOT NULL,
    name         VARCHAR(120) NOT NULL,
    identification VARCHAR(40),
    event_timestamp   TIMESTAMP WITH TIME ZONE,
    CONSTRAINT pk_cliente_proyeccion PRIMARY KEY (client_id)
);

