-- ---------------------------------------------------------------------
-- Base de datos del microservicio de Person y Client
-- ---------------------------------------------------------------------
CREATE DATABASE banco_ms1;

\connect banco_ms1

CREATE TABLE client (
    client_id     VARCHAR(40)  NOT NULL,
    name         VARCHAR(120) NOT NULL,
    gender         VARCHAR(20),
    age           INTEGER,
    identification VARCHAR(40)  NOT NULL,
    address      VARCHAR(200),
    phone       VARCHAR(30),
    password     VARCHAR(120) NOT NULL,
    active         BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT pk_cliente PRIMARY KEY (client_id),
    CONSTRAINT uk_cliente_identificacion UNIQUE (identification)
);

-- Proyeccion local de los movimientosiles recibidos por el evento de dominio.
CREATE TABLE movement_projection (
    movement_id  BIGINT        NOT NULL,
    client_id     VARCHAR(40)   NOT NULL,
    account_number  VARCHAR(30)   NOT NULL,
    amount          NUMERIC(19,2) NOT NULL,
    balance          NUMERIC(19,2) NOT NULL,
    date          DATE          NOT NULL,
    CONSTRAINT pk_movimiento_proyeccion PRIMARY KEY (movement_id)
);

CREATE INDEX idx_movimiento_proyeccion_cliente ON movement_projection (client_id, date);

